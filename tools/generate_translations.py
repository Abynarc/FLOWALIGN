#!/usr/bin/env python3
"""Generate the C++ translation catalog from Source/Translations.json."""
from pathlib import Path
import json
root = Path(__file__).resolve().parents[1]
catalog = json.loads((root / "Source/Translations.json").read_text(encoding="utf-8"))
def literal(value):
    return "u8" + json.dumps(value, ensure_ascii=False)
header = "// Generated by tools/generate_translations.py. Edit Translations.json.\n#pragma once\nnamespace flowui { struct Translation { const char* ru; const char* en; };\ninline constexpr Translation translations[] = {\n"
for russian, english in catalog.items():
    header += "    { " + literal(russian) + ", " + literal(english) + " },\n"
header += "}; }\n"
(root / "Source/LocalisationStrings.h").write_text(header, encoding="utf-8")
